import { readFileSync, writeFileSync, existsSync } from 'node:fs';
// Use the empty SPA shell (app.html). dist/index.html is the prerendered landing and must not be
// served as the worker fallback for /sites, /login, etc.
const src = existsSync('dist/app.html')
  ? readFileSync('dist/app.html', 'utf8')
  : existsSync('dist/index.html') ? readFileSync('dist/index.html', 'utf8') : '';
writeFileSync('src/worker/spa-shell.gen.ts', `/** Generated by scripts/spa-shell.mjs — do not edit. */\nexport const SPA_SHELL = ${JSON.stringify(src)};\n`);
