// Generates the static geo assets used by the Carte page (committed). To regenerate:
//   npm i --no-save world-atlas world-countries all-the-cities && node scripts/build-geo.mjs
// Sources: world-atlas (Natural Earth, public domain), world-countries (ODbL), all-the-cities (GeoNames, CC BY 4.0).
// public/maps/regions.json: ISO 3166-2 names from the iso-3166-2 package + French 2016 regions (generated once, see git history).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const countries = require('world-countries');
const cities = require('all-the-cities');

mkdirSync('public/maps', { recursive: true });
for (const r of ['110m', '50m']) copyFileSync(require.resolve(`world-atlas/countries-${r}.json`), `public/maps/countries-${r}.json`);

const cont = (c) => c.region === 'Africa' ? 'AF' : c.region === 'Europe' ? 'EU' : c.region === 'Asia' ? 'AS' : c.region === 'Oceania' ? 'OC'
  : c.region === 'Americas' ? (c.subregion === 'South America' ? 'SA' : 'NA') : 'AN';
// 193 UN members + the two observer states = the usual "195 countries".
const SOVEREIGN_EXTRA = new Set(['VA', 'PS']);
const rows = countries.map((c) => [c.cca2, c.ccn3 || '', c.translations?.fra?.common || c.name.common, cont(c), Math.round(c.latlng[0] * 10) / 10, Math.round(c.latlng[1] * 10) / 10, c.unMember || SOVEREIGN_EXTRA.has(c.cca2) ? 1 : 0, Math.round(c.area || 0)]);
writeFileSync('src/dashboard/map/countries.gen.ts', `// Generated by scripts/build-geo.mjs from world-countries (ODbL). Do not edit.
// [iso2, iso numeric, French name, continent, lat, lng, sovereign (UN 193 + VA + PS), area km²]
export const COUNTRY_ROWS: [string, string, string, 'AF' | 'EU' | 'AS' | 'OC' | 'NA' | 'SA' | 'AN', number, number, 0 | 1, number][] = ${JSON.stringify(rows)};
`);

const seen = new Set();
const out = [];
for (const c of cities.filter((c) => c.population >= 15000).sort((a, b) => b.population - a.population)) {
  const k = c.country + '|' + c.name;
  if (seen.has(k)) continue;
  seen.add(k);
  out.push([c.name, c.country, Math.round(c.loc.coordinates[0] * 100) / 100, Math.round(c.loc.coordinates[1] * 100) / 100]);
}
writeFileSync('public/maps/cities-15k.json', JSON.stringify(out));
console.log('countries', rows.length, 'sovereign', rows.filter((r) => r[6]).length, 'cities', out.length);
