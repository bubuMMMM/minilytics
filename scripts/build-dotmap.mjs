// Builds src/worker/dotmap.gen.ts: a coarse dot grid of the world (equirectangular, 2.5°) where each land dot
// carries its country's ISO-2 code. The widget « carte » renders it as an SVG without any map library.
// Usage: node scripts/build-dotmap.mjs (needs public/maps/countries-110m.json + src/dashboard/map/countries.gen.ts)
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';
import { geoContains } from 'd3-geo';
const topo = JSON.parse(readFileSync('public/maps/countries-110m.json', 'utf8'));
const gen = readFileSync('src/dashboard/map/countries.gen.ts', 'utf8');
const byNum = new Map([...gen.matchAll(/\["([A-Z]{2})","(\d{3})"/g)].map((m) => [m[2], m[1]]));
const byName = { Kosovo: 'XK', 'N. Cyprus': 'CY', Somaliland: 'SO' };
const feats = feature(topo, topo.objects.countries).features.map((f) => ({ f, cc: byNum.get(String(f.id).padStart(3, '0')) ?? byName[f.properties?.name] })).filter((x) => x.cc);
const STEP = 2.5, W = 360 / STEP, LAT0 = 82.5, LAT1 = -57.5, H = Math.round((LAT0 - LAT1) / STEP) + 1;
// One printable char per cell (no '.', '\\', '~', quotes); '~' escapes the next char for codes past the alphabet.
const ALPHA = Array.from({ length: 91 }, (_, i) => String.fromCharCode(35 + i)).filter((c) => c !== '.' && c !== '\\').join('');
const codes = [];
const index = new Map();
let rows = [];
for (let y = 0; y < H; y++) {
  let row = '';
  const lat = LAT0 - y * STEP;
  for (let x = 0; x < W; x++) {
    const lon = -180 + STEP / 2 + x * STEP;
    const hit = feats.find(({ f }) => geoContains(f, [lon, lat]));
    if (!hit) { row += '.'; continue; }
    if (!index.has(hit.cc)) { index.set(hit.cc, codes.length); codes.push(hit.cc); }
    const i = index.get(hit.cc);
    // two base-64 chars per cell would double the size; 1 char covers 90 symbols with a two-char escape.
    row += i < ALPHA.length ? ALPHA[i] : '~' + ALPHA[i - ALPHA.length];
  }
  rows.push(row);
}
const out = `// Generated by scripts/build-dotmap.mjs from world-atlas 110m. Do not edit.\n` +
  `export const DOT_STEP = ${STEP};\nexport const DOT_LAT0 = ${LAT0};\nexport const DOT_W = ${W};\nexport const DOT_H = ${H};\n` +
  `export const DOT_ALPHA = ${JSON.stringify(ALPHA)};\nexport const DOT_CODES = ${JSON.stringify(codes)};\nexport const DOT_ROWS: string[] = ${JSON.stringify(rows)};\n`;
writeFileSync('src/worker/dotmap.gen.ts', out);
console.log('cells', rows.join('').replace(/\./g, '').length, 'codes', codes.length, 'bytes', out.length);
